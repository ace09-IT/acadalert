                        'External service calls: ' + data.external_service_calls,
                        'Computation: ' + data.computation + ' (formula v' + data.formula_version + ')'
                    ].join('\n'));
                })
                .catch(function (error) {
                    verifyBtn.disabled = false;
                    verifyBtn.innerHTML = original;
                    alert('Verification request failed: ' + error);
                });
        });
    }
    @endif
})();
