    new Chart(canvas.getContext('2d'), {
        type: 'bar',
        data: { labels: chart.labels || ['High', 'Moderate', 'Low'], datasets: datasets },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            plugins: {
                legend: { position: 'bottom' },
                tooltip: {
                    callbacks: {
                        label: function (context) {
                            return context.dataset.label + ': ' + context.parsed.y + ' students';
                        }
                    }
                }
            },
            scales: {
                y: { beginAtZero: true, ticks: { precision: 0 } },
                x: { grid: { display: false } }
            }
        }
    });

    @if(!empty($verifyRoute))
    var verifyBtn = document.getElementById('verifyBtn');
    if (verifyBtn) {
        verifyBtn.addEventListener('click', function () {
            var original = verifyBtn.innerHTML;
            verifyBtn.disabled = true;
            verifyBtn.innerHTML = '<span class="spinner-border spinner-border-sm me-1"></span> Verifying...';

            fetch(@json($verifyRoute), { headers: { 'Accept': 'application/json' } })
                .then(function (response) { return response.json(); })
                .then(function (data) {
                    verifyBtn.disabled = false;
                    verifyBtn.innerHTML = original;

                    if (!data.success) {
                        alert('Verification failed: ' + (data.message || 'unknown error'));
                        return;
                    }

                    alert([
                        'Stored digest:     ' + data.stored_digest,
                        'Recomputed digest: ' + data.recomputed_digest,
                        '',
                        'Snapshot matches its digest: ' + (data.payload_digest_matches ? 'YES' : 'NO'),
